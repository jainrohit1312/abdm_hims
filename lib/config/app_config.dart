  static bool _isInitialized = false;

  static late final SupabaseClient supabaseClient;
  static late final FlutterSecureStorage secureStorage;
  static late final SharedPreferences sharedPreferences;

  // ===========================================================================
  // Supabase Configuration
  // ---------------------------------------------------------------------------
  // Values now resolve dynamically through `SupabaseWebConfig` in this order:
  //   1. `window._env_` (web) — generated by the Vercel build script from the
  //      project environment variables (SUPABASE_URL / SUPABASE_ANON_KEY).
  //   2. `--dart-define` — the same Vercel env vars passed at build time.
  //   3. Local-development fallbacks (see supabase_web_config.dart).
  //
  // NOTE: The anon key is safe to ship to browsers (RLS keeps data protected).
  // NEVER place the service-role key in a Flutter web app.
  // ===========================================================================
  static String get supabaseUrl => SupabaseWebConfig.supabaseUrl;
  static String get supabaseAnonKey => SupabaseWebConfig.supabaseAnonKey;

  // ===========================================================================
  // Firebase Configuration
  // ---------------------------------------------------------------------------
  // Values `android/app/google-services.json` (aur Firebase Console -> Project
  // settings) se aayi hain. Inhe AppConfig mein rakhne se Firebase poore app
  // mein ek hi jagah se initialize hota hai.
  //
  // NOTE: iOS target ke liye `ios/Runner/GoogleService-Info.plist` add karo aur
  // `firebaseAppId` ko iOS app id se update karo (ya Firebase.initializeApp()
  // ko bina options ke call karo jab plist maujood ho).
