  // ---------------------------------------------------------------------------
  // API key DeepSeek platform (https://platform.deepseek.com) se milega.
  // NOTE: Client-side apps mein production API key rakhna safe nahi hota —
  // production ke liye is call ko Supabase Edge Function ke through proxy karo.
  // ===========================================================================
  static String get deepSeekApiKey => SupabaseWebConfig.deepSeekApiKey;
  static const String deepSeekBaseUrl = 'https://api.deepseek.com';
  static const String deepSeekModel = 'deepseek-chat';

  static Future<void> init() async {
    // Guard: safe to call from both main.dart and providers without throwing
    // "Instance is already initialized" from Supabase.
    if (_isInitialized) return;

    // NOTE: Firebase Core is NOT initialized here anymore. Startup stays
    // fast and Firebase is initialized lazily inside
    // `PushNotificationService.initialize` (the only feature that needs FCM).
    // That path has its own duplicate-app guard and silently disables FCM
    // when Firebase is not configured for the current platform/build.

    // Initialize Secure Storage PEHLE — Supabase ka session ab secure storage
    // mein persist hoga (SharedPreferences mein JWT store nahi hoga).
    secureStorage = const FlutterSecureStorage(
      aOptions: AndroidOptions(encryptedSharedPreferences: true),
    );

    // Initialize Supabase with a secure-storage-backed session store.
    await Supabase.initialize(
      url: supabaseUrl,
      anonKey: supabaseAnonKey,
      authOptions: FlutterAuthClientOptions(
        localStorage: SecureLocalStorage(secureStorage),
      ),
    );
    supabaseClient = Supabase.instance.client;

    // Initialize Shared Preferences (non-auth preferences ke liye; auth
    // tokens isme kabhi store nahi kiye jaate).
    sharedPreferences = await SharedPreferences.getInstance();

    _isInitialized = true;
  }
}
